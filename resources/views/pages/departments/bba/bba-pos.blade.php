<h4 class="fw-bold pb-2" data-aos="fade-up" data-aos-delay="300">Program Outcomes (POs)</h4>

<h6>On successful completion of the program, Graduates will be able:</h6>

<p data-aos="fade-up" data-aos-delay="400"><strong>PO1.</strong> To apply the domain knowledge, people skills and technical skills to different scenarios of the Business to achieve desired result.</p>
<p data-aos="fade-up" data-aos-delay="500"><strong>PO2.</strong> To analyze, understand and apply various research tools and techniques in innovate and sustaining Business activities and grow.</p>
<p data-aos="fade-up" data-aos-delay="600"><strong>PO3.</strong> To reduce the gap between industry and academia, with the right blend of theory and practice.</p>
<p data-aos="fade-up" data-aos-delay="700"><strong>PO4.</strong> To nurture their talent for becoming good leaders to be an assets for an organization and operate with entrepreneurial mind-set.</p>
